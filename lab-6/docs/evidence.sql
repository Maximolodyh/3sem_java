-- Проверка схемы после запуска приложения с файловой H2.
SELECT TABLE_NAME FROM INFORMATION_SCHEMA.TABLES
WHERE TABLE_SCHEMA = 'PUBLIC' ORDER BY TABLE_NAME;

SELECT CONSTRAINT_NAME, CONSTRAINT_TYPE
FROM INFORMATION_SCHEMA.TABLE_CONSTRAINTS
WHERE TABLE_SCHEMA = 'PUBLIC' ORDER BY TABLE_NAME, CONSTRAINT_NAME;

SELECT ID, NAME, SURNAME, FACULTY, AGE FROM STUDENTS ORDER BY ID;
SELECT ID, CODE, NAME, HOURS FROM SUBJECTS ORDER BY ID;
